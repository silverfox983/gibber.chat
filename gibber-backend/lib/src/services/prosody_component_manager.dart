import 'dart:async';
import 'dart:io';

class ProsodyComponent {
  final String jid;
  final String secret;

  ProsodyComponent({required this.jid, required this.secret});
}

class ProsodyComponentManager {
  static const String _slidgeComponentsFile = '/etc/prosody/slidge-user-components.conf';
  static const String _prosodyCtl = '/usr/bin/prosodyctl';

  final Map<String, ProsodyComponent> _components = {};

  Future<void> initialize() async {
    await _loadExistingComponents();
  }

  Future<void> _loadExistingComponents() async {
    final file = File(_slidgeComponentsFile);
    if (!await file.exists()) {
      await file.create(recursive: true);
      return;
    }

    final content = await file.readAsString();
    _parseComponents(content);
  }

  void _parseComponents(String content) {
    final componentRegex = RegExp(
      r'Component\s+"([^"]+)"\s*\n\s*component_secret\s*=\s*"([^"]+)"',
      multiLine: true,
    );

    for (final match in componentRegex.allMatches(content)) {
      final jid = match.group(1)!;
      final secret = match.group(2)!;
      _components[jid] = ProsodyComponent(jid: jid, secret: secret);
    }
  }

  String _generateConfig() {
    final buffer = StringBuffer();
    buffer.writeln('-- User-provisioned Slidge Gateway Components (auto-generated by Gibber backend)');
    buffer.writeln('-- Do not edit manually');
    buffer.writeln();

    for (final entry in _components.entries) {
      buffer.writeln('Component "${entry.key}"');
      buffer.writeln('    component_secret = "${entry.value.secret}"');
      buffer.writeln();
    }

    return buffer.toString();
  }

  Future<bool> addComponent(String jid, String secret) async {
    if (_components.containsKey(jid)) {
      print('Component $jid already exists, updating secret');
      _components[jid] = ProsodyComponent(jid: jid, secret: secret);
    } else {
      _components[jid] = ProsodyComponent(jid: jid, secret: secret);
    }

    await _writeConfig();
    final reloaded = await _reloadProsody();
    return reloaded;
  }

  Future<bool> removeComponent(String jid) async {
    if (!_components.containsKey(jid)) {
      return true;
    }

    _components.remove(jid);
    await _writeConfig();
    final reloaded = await _reloadProsody();
    return reloaded;
  }

  Future<void> _writeConfig() async {
    final file = File(_slidgeComponentsFile);
    await file.writeAsString(_generateConfig());
    print('Updated $_slidgeComponentsFile with ${_components.length} components');
  }

  Future<bool> _reloadProsody() async {
    try {
      final result = await Process.run(_prosodyCtl, ['reload']);
      if (result.exitCode == 0) {
        print('Prosody reload successful');
        return true;
      } else {
        print('Prosody reload failed: ${result.stderr}');
        return false;
      }
    } catch (e) {
      print('Failed to reload prosody: $e');
      return false;
    }
  }

  Future<bool> restartProsody() async {
    try {
      final result = await Process.run(_prosodyCtl, ['restart']);
      if (result.exitCode == 0) {
        print('Prosody restart successful');
        return true;
      } else {
        print('Prosody restart failed: ${result.stderr}');
        return false;
      }
    } catch (e) {
      print('Failed to restart prosody: $e');
      return false;
    }
  }

  bool hasComponent(String jid) => _components.containsKey(jid);

  ProsodyComponent? getComponent(String jid) => _components[jid];

  List<ProsodyComponent> getAllComponents() => _components.values.toList();

  int get componentCount => _components.length;

  Future<Map<String, dynamic>> getProsodyStatus() async {
    try {
      final result = await Process.run(_prosodyCtl, ['status']);
      return {
        'running': result.exitCode == 0,
        'output': result.stdout.toString(),
        'components': _components.length,
      };
    } catch (e) {
      return {
        'running': false,
        'error': e.toString(),
        'components': _components.length,
      };
    }
  }
}
